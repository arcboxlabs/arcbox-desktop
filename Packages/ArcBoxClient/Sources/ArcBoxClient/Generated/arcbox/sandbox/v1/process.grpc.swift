// Sandbox process data plane (CORE-55).
//
// An execution is an addressable, resumable process inside a sandbox. It
// survives any client connection: output is offset-addressed per channel, so
// a client that loses its AttachExecution stream re-attaches at its last
// offsets and re-reads without loss; stdin writes are offset-idempotent, so
// a retried WriteStdin never double-feeds the process. Signals, TTY resize,
// and exit status go through the execution id, never through a stream.
//
// This is **data plane**: every call here touches a specific running
// sandbox and carries the process's stdio. The local daemon serves these
// calls and forwards guest operations to the System VM's agent.
// See `sandbox.proto` for the control plane.

